import { readFileSync } from 'node:fs';

/** Document languages. The price quote for the Dig.IT application is Polish only. */
export type Lang = 'pl' | 'en';

/** A fill-in field such as `{{NAZWA_FIRMY}}`: upper-case ASCII, digits, underscores. */
export const PLACEHOLDER = /\{\{[A-Z0-9_]+\}\}/g;

const ESCAPES: Record<string, string> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

export function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/g, (c) => ESCAPES[c] ?? c);
}

/**
 * Escapes text and wraps every `{{FIELD}}` in a highlighted span, so unfilled fields stand
 * out in the PDF and cannot be mistaken for content.
 */
export function text(value: string): string {
  return escapeHtml(value).replace(PLACEHOLDER, (m) => `<span class="field">${m}</span>`);
}

/** Every distinct `{{FIELD}}` left in a string (rendered HTML or plain text), sorted. */
export function findPlaceholders(value: string): string[] {
  return [...new Set(value.match(PLACEHOLDER) ?? [])].sort();
}

/** Money in whole zloty or grosze, PL `12 345,67 zł` / EN `PLN 12,345.67`. */
export function formatMoney(grosze: number, lang: Lang, opts: { decimals?: boolean } = {}): string {
  if (!Number.isInteger(grosze) || grosze < 0) throw new Error(`Invalid amount: ${String(grosze)}`);
  const decimals = opts.decimals ?? grosze % 100 !== 0;
  // Grouping by hand: pl-PL in Intl leaves 4-digit numbers ungrouped ("5000"), which breaks
  // the alignment of price columns. Non-breaking spaces keep amounts on one line.
  const whole = String(Math.floor(grosze / 100)).replace(
    /\B(?=(\d{3})+(?!\d))/g,
    lang === 'pl' ? '\u00a0' : ',',
  );
  const cents = String(grosze % 100).padStart(2, '0');
  const n = decimals ? `${whole}${lang === 'pl' ? ',' : '.'}${cents}` : whole;
  return lang === 'pl' ? `${n}\u00a0zł` : `PLN\u00a0${n}`;
}

/** Range of whole zloty, e.g. `70 000–130 000 zł` / `PLN 70,000–130,000`. */
export function formatRange(minZl: number, maxZl: number, lang: Lang): string {
  const min = formatMoney(minZl * 100, lang);
  const max = formatMoney(maxZl * 100, lang);
  return lang === 'pl'
    ? `${min.replace(/\u00a0zł$/, '')}–${max}`
    : `${min}–${max.replace(/^PLN\u00a0/, '')}`;
}

const repoRoot = new URL('../../', import.meta.url);

/**
 * An on-light brand asset from public/brand/ (generated by `npm run brand:assets`), inline and
 * hidden from assistive tech: `logo-on-light` (logotype) or `mark-on-light` (sygnet).
 */
export function brandSvg(asset: 'logo-on-light' | 'mark-on-light', className: string): string {
  const svg = readFileSync(new URL(`public/brand/${asset}.svg`, repoRoot), 'utf8').trim();
  return svg.replace('<svg ', `<svg class="${className}" aria-hidden="true" focusable="false" `);
}

/** Bulleted list of escaped items (fields highlighted); empty string for no items. */
export function list(items: string[] | undefined): string {
  return items && items.length > 0
    ? `<ul>${items.map((i) => `<li>${text(i)}</li>`).join('')}</ul>`
    : '';
}

/** The "preliminary pricing" badge shown while pricing.json is a draft. */
export function draftBadge(label: string): string {
  return `<p class="draft-badge" data-draft>${escapeHtml(label)}</p>`;
}

export interface DocumentShell {
  lang: Lang;
  title: string;
  /** Stylesheets relative to docs-templates/, e.g. `offer/offer.css`. */
  styles: string[];
  body: string;
  /** Path from the written HTML file back to docs-templates/ (default: out/<dir>/file.html). */
  templatesHref?: string;
}

/** Full HTML document with the `paper` print theme (brand.md). */
export function documentHtml(doc: DocumentShell): string {
  const base = doc.templatesHref ?? '../../docs-templates/';
  const links = ['shared/docs.css', ...doc.styles]
    .map((href) => `<link rel="stylesheet" href="${base}${href}" />`)
    .join('\n    ');
  return `<!doctype html>
<html lang="${doc.lang}" data-theme="paper">
  <head>
    <meta charset="UTF-8" />
    <title>${escapeHtml(doc.title)}</title>
    ${links}
  </head>
  <body>
${doc.body}
  </body>
</html>
`;
}

/** Visible text of an HTML string (tags dropped, entities decoded) for tests and checks. */
export function visibleText(html: string): string {
  return html
    .replace(/<(style|script|title)\b[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;|\u00a0/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim();
}
